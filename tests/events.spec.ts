import { test, expect, type Page } from '@playwright/test'

const storageKey = 'wids.events.v1'
const fixture = () => [1, 2, 3, 4].map(id => ({
  id: `event-${id}`, title: `WiDS event ${id}`, starts_at: '2026-11-12T02:00:00Z', location: 'UBC · Test room', description: 'Full event details and meeting point.', archived: false,
  roles: [
    { id: `role-${id}`, name: 'Setup crew', slots: 2, starts_at: '2026-11-12T01:00:00Z', ends_at: '2026-11-12T02:00:00Z', signups: [{ id: `signup-${id}`, role_id: `role-${id}`, name: 'Alex', created_at: '2026-10-26T00:00:00Z' }] },
    { id: `full-${id}`, name: 'Welcome desk', slots: 1, signups: [{ id: `full-signup-${id}`, role_id: `full-${id}`, name: 'Sam', created_at: '2026-10-26T00:00:00Z' }] },
  ],
}))
async function seed(page: Page) {
  await page.addInitScript(({ key, events }) => { if (!localStorage.getItem(key)) localStorage.setItem(key, JSON.stringify(events)) }, { key: storageKey, events: fixture() })
}
async function fillNewEvent(page: Page) {
  await page.getByLabel('Event name', { exact: true }).fill('Data & donuts')
  await page.getByLabel('Date', { exact: true }).fill('2026-12-12')
  await page.getByLabel('Event start time').fill('17:00')
  await page.getByLabel('Location (optional)').fill('UBC Room 101')
  await page.getByLabel('Role name', { exact: true }).fill('Setup')
  await page.getByLabel('Shift start', { exact: true }).fill('16:00')
  await page.getByLabel('Shift end', { exact: true }).fill('17:00')
  await page.getByLabel('People needed', { exact: true }).fill('2')
}

test('create timed roles, minimize, sign up, persist, archive and restore', async ({ page }) => {
  const supabaseRequests: string[] = []
  page.on('request', request => { if (request.url().includes('supabase.co')) supabaseRequests.push(request.url()) })
  await page.goto('/#/events')
  await page.getByRole('button', { name: '+ Add event', exact: true }).click()
  await fillNewEvent(page)
  await page.getByRole('button', { name: '+ Add role' }).click()
  const secondRole = page.getByRole('group', { name: 'Role 2', exact: true })
  await secondRole.getByLabel('Role name').fill('Welcome desk')
  await secondRole.getByLabel('Shift start').fill('17:00')
  await secondRole.getByLabel('Shift end').fill('19:00')
  await page.getByRole('button', { name: 'Create event', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const card = page.locator('.schedule-card').first()
  await expect(card).toContainText('Data & donuts')
  await expect(card).toContainText('0 / 3 slots filled')
  await card.getByRole('button', { name: 'Expand Data & donuts' }).click()
  await expect(card).toContainText('Welcome desk')
  await card.getByRole('button', { name: 'Minimize Data & donuts' }).click()
  await expect(card.locator('.schedule-details')).toHaveCount(0)
  await page.goto('/')
  await page.getByRole('button', { name: 'Sign up', exact: true }).click()
  await page.getByLabel('Name', { exact: true }).fill('Nina')
  await page.getByLabel('Role', { exact: true }).selectOption({ index: 1 })
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.locator('.event-card')).toContainText('Nina')
  await page.reload()
  await expect(page.locator('.event-card')).toContainText('Nina')
  await page.goto('/#/events')
  await card.getByRole('button', { name: 'Archive event', exact: true }).click()
  await expect(page.locator('.schedule-card')).toHaveCount(0)
  await page.goto('/')
  await expect(page.locator('.event-card')).toHaveCount(0)
  await page.goto('/#/calendar')
  await expect(page.locator('.calendar-event')).toHaveCount(0)
  await page.goto('/#/events')
  await page.getByRole('button', { name: 'Archived (1)', exact: true }).click()
  await page.getByRole('button', { name: 'Restore event', exact: true }).click()
  await page.getByRole('button', { name: 'Active (1)', exact: true }).click()
  await page.getByRole('button', { name: 'Expand Data & donuts' }).click()
  await expect(card).toContainText('Nina')
  expect(supabaseRequests).toEqual([])
})

test('duplicate rejection, full roles, and persistence after reload', async ({ page }) => {
  await seed(page)
  await page.goto('/')
  const card = page.locator('.event-card').first()
  await card.getByRole('button', { name: 'Sign up', exact: true }).click()
  await expect(page.getByLabel('Name', { exact: true })).toBeFocused()
  await expect(page.getByLabel('Role', { exact: true }).locator('option')).toHaveCount(2)
  await page.getByLabel('Name', { exact: true }).fill('  alex  ')
  await page.getByLabel('Role', { exact: true }).selectOption('role-1')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('already signed up')
  await page.getByLabel('Name', { exact: true }).fill('  Nina   Tsai ')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(card).toContainText('Alex, Nina Tsai')
  await expect(card.getByRole('button', { name: 'All roles filled' })).toBeDisabled()
  await page.reload()
  await expect(card).toContainText('Alex, Nina Tsai')
})

test('two tabs cannot overfill the final slot and stay in sync', async ({ page, context }) => {
  await seed(page)
  await page.goto('/')
  const other = await context.newPage()
  await other.goto('/')
  for (const [tab, name] of [[page, 'Nina'], [other, 'Taylor']] as const) {
    await tab.locator('.event-card').first().getByRole('button', { name: 'Sign up', exact: true }).click()
    await tab.getByLabel('Name', { exact: true }).fill(name)
    await tab.getByLabel('Role', { exact: true }).selectOption('role-1')
  }
  await Promise.all([page.getByRole('button', { name: 'Save', exact: true }).click(), other.getByRole('button', { name: 'Save', exact: true }).click()])
  await expect.poll(() => page.evaluate(key => JSON.parse(localStorage.getItem(key)!)[0].roles[0].signups.length, storageKey)).toBe(2)
  await page.reload()
  await other.reload()
  for (const tab of [page, other]) await expect(tab.locator('.event-card').first().getByRole('button', { name: 'All roles filled' })).toBeDisabled()
})

test('invalid role timeframe is rejected; overnight shift can be created', async ({ page }) => {
  await page.goto('/#/events')
  await page.getByRole('button', { name: '+ Add event', exact: true }).click()
  await fillNewEvent(page)
  await page.getByLabel('Shift start', { exact: true }).fill('23:00')
  await page.getByLabel('Shift end', { exact: true }).fill('01:00')
  await page.getByRole('button', { name: 'Create event', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('must end after it starts')
  await page.getByLabel('Ends next day').check()
  await page.getByRole('button', { name: 'Create event', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: 'Expand Data & donuts' }).click()
  await expect(page.locator('.schedule-details')).toContainText('(next day)')
})

test('375px create form and navigation stay within the screen', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await seed(page)
  await page.goto('/')
  await page.getByRole('button', { name: 'Open navigation menu' }).click()
  await page.getByRole('link', { name: 'Calendar', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Team calendar' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Open navigation menu' }).click()
  await page.getByRole('link', { name: 'Event dashboards', exact: true }).click()
  await expect(page.locator('.schedule-card')).toHaveCount(4)
  const heights = await page.locator('.schedule-card').evaluateAll(cards => cards.map(card => card.getBoundingClientRect().height))
  expect(new Set(heights).size).toBe(1)
  await page.getByRole('button', { name: '+ Add event', exact: true }).click()
  await fillNewEvent(page)
  const box = await page.getByRole('dialog').boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(375)
  await page.getByRole('button', { name: 'Create event', exact: true }).click()
  await expect(page.locator('.schedule-card')).toHaveCount(5)
})

test('corrupt local data is preserved and never silently overwritten', async ({ page }) => {
  await page.addInitScript(key => localStorage.setItem(key, 'broken data'), storageKey)
  await page.goto('/#/events')
  await expect(page.getByRole('alert')).toContainText('could not be read')
  await page.getByRole('button', { name: '+ Add event', exact: true }).click()
  await fillNewEvent(page)
  await page.getByRole('button', { name: 'Create event', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('could not be read')
  expect(await page.evaluate(key => localStorage.getItem(key), storageKey)).toBe('broken data')
})
